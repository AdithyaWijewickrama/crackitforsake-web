"""Extract each question's original text and diagrams from the combined PDF.

Writes img/qNN_K.png and originals.js (window.ORIGINALS = {q1: {text, images}}).
Needs PyMuPDF:  python -m pip install pymupdf
    python tools/build_originals.py ../HaXtreme_5.0_All_40_Questions.pdf
"""
import json, os, sys
import pymupdf

# first PDF page (0-based) of each question, in question order
FIRST_PAGE = [0, 1, 2, 3, 4, 5, 7, 9, 11, 12, 14, 15, 17, 18, 27, 32, 36, 39, 40, 42,
              44, 46, 48, 50, 53, 56, 58, 59, 61, 63, 64, 66, 68, 70, 72, 74, 75, 76, 77, 78]

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
pdf = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "..", "HaXtreme_5.0_All_40_Questions.pdf")
doc = pymupdf.open(pdf)
os.makedirs(os.path.join(root, "img"), exist_ok=True)
out = {}
for qi, first in enumerate(FIRST_PAGE):
    last = FIRST_PAGE[qi + 1] if qi + 1 < len(FIRST_PAGE) else doc.page_count
    text, images = [], []
    for pno in range(first, last):
        page = doc[pno]
        text.append(page.get_text())
        for img in page.get_images(full=True):
            info = doc.extract_image(img[0])
            if info["width"] < 300:  # skip the small HackerRank logo
                continue
            name = "img/q%02d_%d.%s" % (qi + 1, len(images) + 1, info["ext"])
            open(os.path.join(root, name), "wb").write(info["image"])
            images.append(name)
    # drop the "1/2" page footers
    lines = [l for t in text for l in t.splitlines() if not __import__("re").fullmatch(r"\s*\d+/\d+\s*", l)]
    out["q%d" % (qi + 1)] = {"text": "\n".join(lines).strip(), "images": images}
js = "// Generated by tools/build_originals.py. Do not edit.\nwindow.ORIGINALS = " + json.dumps(out, ensure_ascii=False, indent=1).replace("</", r"<\/") + ";\n"
open(os.path.join(root, "originals.js"), "w", encoding="utf-8", newline="\n").write(js)
print("originals.js:", len(js), "bytes;", sum(len(v["images"]) for v in out.values()), "images")
