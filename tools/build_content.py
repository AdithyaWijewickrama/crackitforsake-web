"""Embed the question cards from HaXtreme_Defense_Guide.html into content.js.

index.html cannot fetch() a local file when opened via file://, so app.js reads
window.LEGACY_HTML instead. Re-run after editing HaXtreme_Defense_Guide.html:
    python tools/build_content.py
"""
import json, os, re

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, "HaXtreme_Defense_Guide.html"), encoding="utf-8").read()
m = re.search(r"<main>(.*)</main>", src, re.S)
body = m.group(1)
out = "// Generated by tools/build_content.py from HaXtreme_Defense_Guide.html. Do not edit.\n"
out += "window.LEGACY_HTML = " + json.dumps(body, ensure_ascii=False).replace("</", r"<\/") + ";\n"
open(os.path.join(root, "content.js"), "w", encoding="utf-8", newline="\n").write(out)
print("content.js written,", len(out), "bytes")
